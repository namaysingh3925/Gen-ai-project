#!/usr/bin/env node
/**
 * Minimal stand-in for the Gemini `generateContent` endpoint, for offline demos and end-to-end tests.
 *
 *   node scripts/fake-gemini.mjs            # listens on :8787
 *   GEMINI_BASE_URL=http://127.0.0.1:8787 GEMINI_API_KEY=fake npm run dev
 *
 * It inspects the prompt, figures out which document was requested and returns plausible Markdown.
 * Env knobs: PORT, FAKE_DELAY_MS (latency), FAKE_FAIL_FIRST=<n> (answer the first n calls with 503).
 */
import http from "node:http";

const port = Number(process.env.PORT) || 8787;
const delay = Number(process.env.FAKE_DELAY_MS) || 400;
let failFirst = Number(process.env.FAKE_FAIL_FIRST) || 0;
let calls = 0;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function docFor(prompt) {
  const task = prompt.split("=== TASK ===")[1] ?? "";
  const name = /^name: (.+)$/m.exec(prompt)?.[1] ?? "project";
  if (/ARCHITECTURE\.md/.test(task))
    return `# ${name} - Architecture\n\n## Overview\nA small service split into an API layer and a storage layer.\n\n## Components\n| Component | Path | Responsibility |\n|---|---|---|\n| API | src/ | Handles requests |\n| Store | lib/ | Persists data |\n\n\`\`\`mermaid\nflowchart TD\n  A["Client"] --> B["API routes"]\n  B --> C["Service layer"]\n  C --> D["Data store"]\n\`\`\`\n\n## Data flow\n1. The client calls the API.\n2. The service layer validates and persists.\n`;
  if (/API\.md/.test(task)) return `# ${name} API\n\n## Endpoints\n### GET /health\nReturns service status.\n\n\`\`\`bash\ncurl http://localhost:3000/health\n\`\`\`\n`;
  if (/CONTRIBUTING\.md/.test(task)) return `# Contributing to ${name}\n\n## Setup\n\`\`\`bash\nnpm install\nnpm test\n\`\`\`\n\n## Pull requests\nFork, branch, commit, open a PR.\n`;
  if (/CHANGELOG\.md/.test(task)) return `# Changelog\n\n## [Unreleased]\n### Added\n- Initial work (abc1234)\n`;
  return `\`\`\`markdown\n# ${name}\n\nA concise demo README generated by the fake Gemini server.\n\n## Features\n- Fast\n- Documented\n\n## Getting Started\n\n### Installation\n\`\`\`bash\nnpm install\n\`\`\`\n\n## Usage\n\`\`\`bash\nnpm start\n\`\`\`\n\n## Contributing\nPRs welcome.\n\n## License\nSee the LICENSE file.\n\`\`\`\n`;
}

http
  .createServer(async (req, res) => {
    if (req.method !== "POST" || !/:generateContent$/.test(req.url ?? "")) {
      res.writeHead(404, { "Content-Type": "application/json" }).end(JSON.stringify({ error: { message: "not found", status: "NOT_FOUND" } }));
      return;
    }
    let raw = "";
    for await (const chunk of req) raw += chunk;
    calls++;
    const reply = (status, body) => res.writeHead(status, { "Content-Type": "application/json" }).end(JSON.stringify(body));

    if (!req.headers["x-goog-api-key"]) return reply(403, { error: { message: "API key missing", status: "PERMISSION_DENIED" } });
    if (failFirst > 0) {
      failFirst--;
      return reply(503, { error: { message: "The model is overloaded.", status: "UNAVAILABLE" } });
    }
    let body;
    try {
      body = JSON.parse(raw);
    } catch {
      return reply(400, { error: { message: "bad json", status: "INVALID_ARGUMENT" } });
    }
    const prompt = body?.contents?.[0]?.parts?.[0]?.text ?? "";
    await sleep(delay);
    const text = docFor(prompt);
    console.log(`[fake-gemini] call #${calls} -> ${text.length} chars`);
    reply(200, {
      candidates: [{ content: { role: "model", parts: [{ text }] }, finishReason: "STOP" }],
      usageMetadata: { promptTokenCount: Math.ceil(prompt.length / 4), candidatesTokenCount: Math.ceil(text.length / 4) },
    });
  })
  .listen(port, "127.0.0.1", () => console.log(`[fake-gemini] listening on http://127.0.0.1:${port}`));
